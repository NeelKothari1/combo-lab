import {spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const directory=fileURLToPath(new URL('.',import.meta.url));
const result=spawnSync('cargo',['run','--release','--locked','--manifest-path',`${directory}Cargo.toml`],{
  cwd:directory,
  encoding:'utf8',
  maxBuffer:16*1024*1024,
  env:{...process.env,RUSTFLAGS:`${process.env.RUSTFLAGS||''} -A dangerous_implicit_autorefs`.trim()}
});
process.stderr.write(result.stderr||'');
if(result.status!==0)throw new Error(`Solver generator failed (${result.status}): ${result.error||''}`);
const {meta,scenarios}=JSON.parse(result.stdout);
meta.inputsSha256=createHash('sha256').update(readFileSync(new URL('./inputs.json',import.meta.url))).digest('hex');
const file=`// Generated by scripts/solver-library/build.mjs. Do not hand-edit solver results.\n// Numerical results from b-inary/postflop-solver; provenance and scope are included below.\nexport const solverLibraryMeta=${JSON.stringify(meta,null,2)};\nexport const solverScenarios=[\n${scenarios.map(s=>JSON.stringify(s)).join(',\n')}\n];\n`;
writeFileSync(new URL('../../dist/solver-data.js',import.meta.url),file);
console.log(`Generated ${scenarios.length} solver range exercises from ${meta.gameCount} river games.`);
